// Shared contract suite for DecompilerPort (A-22, K-008, K-501).
// The fake in tests/fakes and the extdecomp worker adapter in
// src/adapters/extdecomp run this same suite, so the fake stays honest
// against the port contract: successful decompilation links functions to
// selectors in the input bytecode, and every pathological outcome yields
// its typed error branch without mutating the input.
import { describe, expect, test } from "vitest";
import * as fc from "fast-check";
import type { DecompilerError, DecompilerPort } from "../../src/ports/decompiler.ts";
import { Bytecode, CodeHash, RequestId, Timestamp, BlockNumber } from "../../src/domain/types.ts";
import type { Result } from "../../src/domain/result.ts";

// Scenario driver shared by the fake and the worker adapter: each scenario
// selects one canned outcome or one fake-worker mode with the same typed
// branch, so fake and adapter prove equal outcomes in the suite.
export type DecompilerContractScenario =
  | "success"
  | "timeout"
  | "resource-limit"
  | "process-error"
  | "invalid-output"
  | "output-too-large";

function mustOk<T, E extends { message: string }>(result: Result<T, E>): T {
  if (!result.ok) {
    throw new Error(`expected ok, got error: ${result.error.message}`);
  }
  return result.value;
}

// Dispatcher window with a paired PUSH4 selector plus a trailing
// SELFDESTRUCT, so the same bytecode feeds the fast-path signals and the
// deepening: extractSelectors finds 0xa9059cbb and detectCapabilities
// reports the storage-write/selfdestruct capability beside it.
export const DISPATCHER_BYTECODE = "0x8063a9059cbb1461005b57ff";

function fixedContext() {
  return {
    requestId: mustOk(RequestId.parse("123e4567-e89b-12d3-a456-426614174000")),
    deadline: mustOk(Timestamp.of(4102444800000)),
    block: mustOk(BlockNumber.of(24000000)),
  };
}

const ERROR_SCENARIOS: ReadonlyArray<{
  readonly scenario: DecompilerContractScenario;
  readonly kind: DecompilerError["kind"];
}> = [
  { scenario: "timeout", kind: "timeout" },
  { scenario: "resource-limit", kind: "resource-limit" },
  { scenario: "process-error", kind: "process-error" },
  { scenario: "invalid-output", kind: "invalid-output" },
  { scenario: "output-too-large", kind: "output-too-large" },
];

export function runDecompilerPortContract(
  label: string,
  makePort: (scenario: DecompilerContractScenario) => DecompilerPort,
  options: { timeoutMs?: number | undefined } = {},
): void {
  const timeout = options.timeoutMs ?? 5000;
  describe(`DecompilerPort contract: ${label}`, () => {
    test(
      "success links functions to selectors in the input bytecode",
      async () => {
        const port = makePort("success");
        const bytecode = mustOk(Bytecode.parse(DISPATCHER_BYTECODE));
        const codeHash = mustOk(CodeHash.of(bytecode));
        const before = Array.from(bytecode);
        const result = await port.decompile(bytecode, codeHash, fixedContext());
        expect(Array.from(bytecode)).toEqual(before);
        expect(result.ok).toBe(true);
        if (!result.ok) {
          return;
        }
        expect(result.value.codeHash as string).toBe(codeHash as string);
        expect(result.value.functions.length).toBeGreaterThan(0);
        const inputHex = DISPATCHER_BYTECODE.slice(2).toLowerCase();
        for (const fn of result.value.functions) {
          expect(inputHex).toContain((fn.selector as string).slice(2).toLowerCase());
          expect(fn.snippet.text.length).toBeGreaterThan(0);
          expect(Number.isInteger(fn.snippet.line) && fn.snippet.line >= 0).toBe(true);
          expect(fn.snippet.selector as string).toBe(fn.selector as string);
        }
      },
      timeout,
    );

    for (const { scenario, kind } of ERROR_SCENARIOS) {
      test(
        `scenario ${scenario} yields typed error ${kind} without mutating the input`,
        async () => {
          const port = makePort(scenario);
          const bytecode = mustOk(Bytecode.parse(DISPATCHER_BYTECODE));
          const codeHash = mustOk(CodeHash.of(bytecode));
          const before = Array.from(bytecode);
          const result = await port.decompile(bytecode, codeHash, fixedContext());
          expect(Array.from(bytecode)).toEqual(before);
          expect(result.ok).toBe(false);
          if (result.ok) {
            return;
          }
          expect(result.error.kind).toBe(kind);
          expect(result.error.message.length).toBeGreaterThan(0);
        },
        timeout,
      );
    }

    test(
      "property: generated bytecodes pass through unchanged with a matching code hash",
      async () => {
        await fc.assert(
          fc.asyncProperty(
            fc.array(fc.integer({ min: 0, max: 255 }), { minLength: 1, maxLength: 24 }),
            async (bytes) => {
              const hex = `0x${bytes.map((b) => b.toString(16).padStart(2, "0")).join("")}`;
              const bytecode = mustOk(Bytecode.parse(hex));
              const codeHash = mustOk(CodeHash.of(bytecode));
              const before = Array.from(bytecode);
              const port = makePort("success");
              const result = await port.decompile(bytecode, codeHash, fixedContext());
              expect(Array.from(bytecode)).toEqual(before);
              expect(result.ok).toBe(true);
              if (!result.ok) {
                return;
              }
              expect(result.value.codeHash as string).toBe(codeHash as string);
            },
          ),
          { seed: 8011, numRuns: 10 },
        );
      },
      timeout,
    );
  });
}
